using System.Text;
using System.Text.RegularExpressions;

namespace GotX.Port;

/// <summary>HTML tree to a GotX C# skeleton (View subclass + Render). A starting point: every TODO comment needs a human decision.</summary>
public sealed partial class HtmlToCs
{
    static readonly HashSet<string> Ignored = ["head", "title", "meta", "link", "script", "style", "noscript", "template", "base"];
    static readonly HashSet<string> Inline = ["span", "a", "strong", "em", "b", "i", "small", "code", "label", "kbd", "mark", "abbr", "sub", "sup", "u", "s"];
    static readonly HashSet<string> Table = ["table", "thead", "tbody", "tfoot", "tr", "td", "th", "caption", "colgroup", "col"];

    readonly List<string> _icons = [];
    readonly List<string> _images = [];
    readonly List<string> _notes = [];
    readonly StringBuilder _unsupported = new();
    int _icon, _image;
    bool _sawStyle, _sawScript;

    /// <summary>Line of one emitted element: the text and whether it ends in a // comment (so closers need their own line).</summary>
    sealed record Line(string Text, bool Comment = false);

    public static string Generate(string html, string ns = "Ported", string view = "PortedView") =>
        new HtmlToCs().Build(HtmlParser.Parse(html), ns, view);

    string Build(HtmlNode root, string ns, string view)
    {
        _sawStyle = HasTag(root, "style");
        _sawScript = HasTag(root, "script");
        var top = (HtmlNode)(Find(root, "body") ?? root);
        var roots = top.Children.Where(Keep).ToList();
        List<Line> body;
        if (roots.Count == 1 && !roots[0].IsText) body = Element(roots[0]);
        else
        {
            if (roots.Count > 1) _notes.Add("several top-level nodes: wrapped in a root Div");
            body = [new Line("w.Div().Class(\"size-full\") // TODO root classes")];
            AddChildren(body, roots);
        }

        var sb = new StringBuilder();
        sb.AppendLine("// Generated by GotX.Port html: a skeleton. Review every TODO / UNSUPPORTED comment; compile and fix.");
        foreach (string n in _notes) sb.AppendLine("// note: " + n);
        if (_sawStyle) sb.AppendLine("// note: <style> ignored (translate its rules into Tailwind classes by hand)");
        if (_sawScript) sb.AppendLine("// note: <script> ignored (behaviour goes into handlers: .OnClick(this, static (v, e) => ...))");
        sb.AppendLine("using GotX;");
        sb.AppendLine("using GotX.Components;");
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine($"public sealed class {view} : View");
        sb.AppendLine("{");
        if (_icons.Count > 0)
        {
            sb.AppendLine("    // Create icons once (static readonly), never inside Render.");
            sb.AppendLine("    static class Icons");
            sb.AppendLine("    {");
            foreach (string i in _icons) sb.AppendLine("        " + i);
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        foreach (string i in _images) sb.AppendLine("    " + i);
        if (_images.Count > 0) sb.AppendLine();
        sb.AppendLine("    public override Div Render(Window w) =>");
        for (int k = 0; k < body.Count; k++)
            sb.AppendLine("        " + body[k].Text + (k == body.Count - 1 ? ";" : ""));
        sb.AppendLine("}");
        return sb.ToString().Replace("\r\n", "\n");
    }

    // ---------- tree walk ----------

    static bool Keep(HtmlNode n) => n.IsText ? n.Text.Trim().Length > 0 : !Ignored.Contains(n.Tag);

    static bool HasTag(HtmlNode n, string tag) => n.Tag == tag || n.Children.Any(c => HasTag(c, tag));

    static HtmlNode? Find(HtmlNode n, string tag)
    {
        if (n.Tag == tag) return n;
        foreach (var c in n.Children) if (Find(c, tag) is { } f) return f;
        return null;
    }

    List<Line> Element(HtmlNode e)
    {
        var comments = new List<string>();
        var classes = new List<string>(HtmlParser.Decode(e.Attr("class") ?? "").Split((char[])[' ', '\t', '\r', '\n'], StringSplitOptions.RemoveEmptyEntries));
        string head;
        var chain = new StringBuilder();
        bool leafOnly = false;

        switch (e.Tag)
        {
            case "svg":
            {
                var info = SvgIcon.Convert(e);
                string name = $"Icon{++_icon}";
                _icons.Add($"public static readonly VectorPath {name} = {info.Factory};");
                foreach (string n in info.Notes) comments.Add($"{name}: {n}");
                head = $"w.Path(Icons.{name})";
                leafOnly = true;
                break;
            }
            case "img":
            {
                string name = $"Image{++_image}";
                _images.Add($"static readonly ImageSource {name} = null!; // TODO ImageSource.FromPngFile(...) for src=\"{Esc(e.Attr("src") ?? "")}\" (PNG only)");
                comments.Add($"img alt=\"{Esc(e.Attr("alt") ?? "")}\" src=\"{Esc(e.Attr("src") ?? "")}\": add object-cover/rounded-* on the class list as needed");
                head = $"w.Image({name})";
                leafOnly = true;
                break;
            }
            default:
                head = "w.Div()";
                break;
        }

        AddUaClasses(e, classes, comments);
        chain.Append(head);
        if (classes.Count > 0) chain.Append($".Class(\"{Esc(string.Join(' ', classes))}\")");
        string? key = e.Attr("id");
        if (!string.IsNullOrEmpty(key)) chain.Append($".Key(\"{Esc(key)}\")");
        else if (e.Attr("data-slot") is { Length: > 0 } slot) comments.Add($"key candidate: data-slot=\"{Esc(slot)}\"");
        if (e.Attr("aria-label") is { Length: > 0 } al) comments.Add($"key candidate / a11y label: aria-label=\"{Esc(al)}\"");
        Describe(e, chain, comments);

        string bad = string.Join(", ", classes.Where(ClassExtractor.IsClassToken).Where(t => !ClassAudit.IsSupported(t)));
        var lines = new List<Line>();
        foreach (string c in comments) lines.Add(new Line("// " + c));

        var kids = e.Children.Where(Keep).ToList();
        if (kids.Any(k => k.IsText) && kids.Any(k => !k.IsText && Inline.Contains(k.Tag)))
            lines.Add(new Line("// TODO inline: text run mixes text with inline elements (GotX has no inline flow): split into a flex flex-wrap row or separate text children"));

        string first = chain.ToString();
        bool single = kids.Count == 1 && kids[0].IsText;
        if (leafOnly || e.Tag is "textarea" or "select") kids.Clear();
        if (single && !leafOnly) first += $".Child(\"{Esc(Collapse(kids[0].Text))}\")";
        var main = new Line(first + (bad.Length > 0 ? $" // UNSUPPORTED: {bad}" : ""), bad.Length > 0);
        lines.Add(main);
        if (!single) AddChildren(lines, kids);
        // Comment lines precede the element: only the first line of `lines` after them is the chain head.
        return lines;
    }

    void AddChildren(List<Line> lines, List<HtmlNode> kids)
    {
        foreach (var k in kids)
        {
            if (k.IsText) { string t = Collapse(k.Text); if (t.Length > 0) Append(lines, new List<Line> { new Line($".Child(\"{Esc(t)}\")") }, false); continue; }
            Append(lines, Element(k), true);
        }
    }

    /// <summary>Appends a child expression: comment lines stay at member level, the chain is wrapped in .Child( ... ).</summary>
    static void Append(List<Line> into, List<Line> child, bool wrap)
    {
        if (!wrap) { foreach (var l in child) into.Add(new Line("    " + l.Text, l.Comment)); return; }
        int head = child.FindIndex(l => !l.Text.StartsWith("//"));
        for (int i = 0; i < head; i++) into.Add(new Line("    " + child[i].Text));
        for (int i = head; i < child.Count; i++)
            into.Add(new Line("    " + (i == head ? ".Child(" : "") + child[i].Text, child[i].Comment));
        var last = into[^1];
        if (last.Comment) into.Add(new Line("    )"));
        else into[^1] = new Line(last.Text + ")");
    }

    // ---------- element specifics ----------

    static void AddUaClasses(HtmlNode e, List<string> classes, List<string> comments)
    {
        void Ua(string cls, string why, string? unlessPrefix)
        {
            if (unlessPrefix is not null && classes.Any(c => Workarounds.Core(c).StartsWith(unlessPrefix, StringComparison.Ordinal))) return;
            classes.Add(cls);
            comments.Add($"UA default <{e.Tag}> added: {cls} ({why})");
        }
        switch (e.Tag)
        {
            case "strong" or "b": Ua("font-bold", "Tailwind preflight keeps bolder; GotX has no UA sheet", "font-"); break;
            case "em" or "i": Ua("italic", "GotX has no UA sheet", "italic"); break;
            case "code" or "pre" or "kbd" or "samp": Ua("font-mono", "GotX has no UA sheet", "font-"); break;
            case "small": comments.Add("UA default <small> is 80% font-size: set text-xs/text-sm explicitly"); break;
            case "h1" or "h2" or "h3" or "h4" or "h5" or "h6": comments.Add("preflight resets heading size/weight/margins: the class string is the only styling (GotX has no UA sheet either)"); break;
            case "p": comments.Add("UA <p> margins are reset by preflight; spacing comes from the parent gap-*/space-y-* (space-y approximated)"); break;
            case "ul" or "ol": comments.Add("list markers/padding are reset by preflight and unsupported in GotX: add a bullet/number child per li if wanted"); break;
            case "a": comments.Add($"a href=\"{Esc(e.Attr("href") ?? "")}\": no navigation in GotX; add cursor-pointer + .OnClick handler, link colour/underline come from classes"); break;
            case "hr": comments.Add("hr: Ui.Separator(w) gives the shadcn separator"); break;
            case "br": comments.Add("br: line break: split into two text children in a flex flex-col"); break;
            case "table" or "thead" or "tbody" or "tfoot" or "tr" or "td" or "th" or "caption":
                if (e.Tag == "table") comments.Add("table: GotX has no table layout; use Ui.Table* (GotX.Components) or grid grid-cols-[..] rows");
                break;
        }
        if (!Table.Contains(e.Tag) && !Known.Contains(e.Tag) && e.Tag is not ("svg" or "img"))
            comments.Add($"unknown/custom tag <{e.Tag}>: mapped to a plain Div");
    }

    static readonly HashSet<string> Known =
    [
        "div", "section", "main", "header", "footer", "nav", "aside", "article", "ul", "ol", "li", "form", "fieldset", "p", "h1", "h2", "h3", "h4", "h5", "h6",
        "span", "a", "button", "label", "small", "strong", "em", "code", "pre", "b", "i", "legend", "figure", "figcaption", "blockquote", "dl", "dt", "dd",
        "input", "textarea", "select", "option", "optgroup", "hr", "br", "kbd", "samp", "mark", "abbr", "sub", "sup", "u", "s", "details", "summary", "dialog", "body", "html",
    ];

    static void Describe(HtmlNode e, StringBuilder chain, List<string> comments)
    {
        switch (e.Tag)
        {
            case "button":
                comments.Add("TODO shadcn-like button? Ui.Button(w, \"label\", ButtonVariant.Default, ButtonSize.Default) replaces this Div");
                chain.Append(".Focusable().OnClick(this, static (v, e) => { /* TODO */ })");
                if (e.Has("disabled")) chain.Append(".Disabled(true)");
                break;
            case "input": comments.Add(InputHint(e)); break;
            case "textarea": comments.Add($"TODO textarea{Attrs(e, "placeholder", "rows", "disabled")} -> GotX.Components.Textarea (App.New in OnCreated, w.View(_x))"); break;
            case "select": comments.Add($"TODO select{Attrs(e, "disabled")} -> NativeSelect (simple) or Select (popover); options: {string.Join(" | ", Options(e))}"); break;
            case "label" when e.Attr("for") is { } f: comments.Add($"label for=\"{Esc(f)}\": Ui.Label(w, \"...\", inputEntity) focuses the Input/Textarea entity on click (or w.FocusKey)"); break;
            case "a" when e.Attr("href") is not null: chain.Append(".Focusable().OnClick(this, static (v, e) => { /* TODO navigate */ })"); break;
        }
        if (e.Attr("title") is { Length: > 0 } t) comments.Add($"title=\"{Esc(t)}\": Tooltip (GotX.Components.Tooltip)");
    }

    static string InputHint(HtmlNode e)
    {
        string type = (e.Attr("type") ?? "text").ToLowerInvariant();
        string target = type switch
        {
            "checkbox" => "Checkbox (or Switch if role=switch)",
            "radio" => "RadioGroup (one view for all radios of the name)",
            "range" => "Slider",
            "submit" or "button" or "reset" => "Ui.Button(w, \"" + Esc(e.Attr("value") ?? "") + "\")",
            "file" or "color" or "date" or "datetime-local" or "time" or "month" or "week" => "no direct equivalent (date: DatePicker/Calendar; file/color: none)",
            "hidden" => "drop (no DOM form state)",
            _ => "Input (GotX.Components; type=password/email/number are plain text entry)",
        };
        return $"TODO input type={type}{Attrs(e, "placeholder", "value", "name", "disabled", "checked", "min", "max")} -> {target}";
    }

    static string Attrs(HtmlNode e, params string[] names)
    {
        var sb = new StringBuilder();
        foreach (string n in names)
            if (e.Has(n)) sb.Append(' ').Append(n).Append(e.Attr(n) is { Length: > 0 } v ? $"=\"{Esc(v)}\"" : "");
        return sb.ToString();
    }

    static IEnumerable<string> Options(HtmlNode e)
    {
        foreach (var c in e.Children)
        {
            if (c.Tag == "option") yield return Collapse(string.Concat(c.Children.Select(x => x.Text)));
            else foreach (string o in Options(c)) yield return o;
        }
    }

    // ---------- text ----------

    [GeneratedRegex(@"[ \t\r\n\f]+")]
    private static partial Regex Ws();

    public static string Collapse(string s) => Ws().Replace(s, " ").Trim();

    static string Esc(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", "\\n").Replace("\u00A0", "\\u00A0");
}
