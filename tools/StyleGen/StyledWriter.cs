using System.Globalization;
using System.Text;

/// <summary>
/// Sinh Styled.g.cs: mỗi utility có 2 dạng (trên handle và trên ref Style). Danh sách utility chia theo nhóm ở các file
/// StyledWriter.Layout / .Spacing / .Visual; thứ tự gọi trong <see cref="Write"/> là thứ tự trong file sinh ra.
/// </summary>
static partial class StyledWriter
{
    static readonly CultureInfo inv = CultureInfo.InvariantCulture;
    static readonly StringBuilder sb = new();

    static string F(float v) => v.ToString("0.####", inv) + "f";

    static void Util(string name, string body, string doc, string param = "", string arg = "")
    {
        string p = param.Length > 0 ? ", " + param : "";
        sb.AppendLine($"    /// <summary>{doc}</summary>");
        sb.AppendLine($"    public static ref Style {name}(this ref Style s{p}) {{ {body} return ref s; }}");
        sb.AppendLine($"    /// <summary>{doc}</summary>");
        sb.AppendLine($"    public static T {name}<T>(this T e{p}) where T : IStyled {{ e.Style.{name}({arg}); return e; }}");
    }

    public static void Write(string outDir)
    {
        sb.AppendLine("// <auto-generated> bởi tools/StyleGen. Đừng sửa tay. </auto-generated>");
        sb.AppendLine("namespace GotX;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>Utility kiểu Tailwind, mỗi utility có 2 dạng: trên handle (Div) và trên ref Style (dùng trong Hover).</summary>");
        sb.AppendLine("public static partial class Styled");
        sb.AppendLine("{");
        Layout();
        Spacing();
        Visual();
        sb.AppendLine("}");
        File.WriteAllText(Path.Combine(outDir, "Styled.g.cs"), sb.ToString());
    }
}