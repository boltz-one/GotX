using System.Text;

/// <summary>Sinh Tw.g.cs – bảng màu Tailwind tham chiếu Theme.Colors (một nguồn duy nhất, sửa theme là đổi luôn).</summary>
static class TwWriter
{
    public static void Write(string outDir)
    {
        string[] families = ["slate", "gray", "zinc", "neutral", "stone", "red", "orange", "amber", "yellow", "lime", "green",
            "emerald", "teal", "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose"];
        int[] steps = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
        var tw = new StringBuilder();
        tw.AppendLine("// <auto-generated> bởi tools/StyleGen. Đừng sửa tay. </auto-generated>");
        tw.AppendLine("namespace GotX;");
        tw.AppendLine();
        tw.AppendLine("/// <summary>Bảng màu Tailwind: <c>Tw.Blue500</c> (giá trị lấy từ <see cref=\"Theme.Colors\"/>).</summary>");
        tw.AppendLine("public static class Tw");
        tw.AppendLine("{");
        tw.AppendLine("    public static readonly Rgba White = Rgba.White;");
        tw.AppendLine("    public static readonly Rgba Black = Rgba.Black;");
        tw.AppendLine("    public static readonly Rgba Transparent = Rgba.Transparent;");
        foreach (var f in families)
            foreach (var st in steps)
                tw.AppendLine($"    public static readonly Rgba {char.ToUpperInvariant(f[0])}{f[1..]}{st} = Theme.Colors[\"{f}-{st}\"];");
        tw.AppendLine("}");
        File.WriteAllText(Path.Combine(outDir, "Tw.g.cs"), tw.ToString());
    }
}
